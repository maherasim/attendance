CREATE DATABASE IF NOT EXISTS `vehari_uc_attendance`
  CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE `vehari_uc_attendance`;

DROP TABLE IF EXISTS `attendance`;
DROP TABLE IF EXISTS `uc_offices`;

CREATE TABLE `uc_offices` (
  `uc_no` INT UNSIGNED NOT NULL,
  `name` VARCHAR(255) NOT NULL,
  `tehsil` VARCHAR(64) NOT NULL,
  `lat` DECIMAL(10,7) NOT NULL,
  `lng` DECIMAL(10,7) NOT NULL,
  PRIMARY KEY (`uc_no`),
  KEY `idx_tehsil` (`tehsil`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE `attendance` (
  `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  `created_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `uc_no` INT UNSIGNED NOT NULL,
  `uc_name` VARCHAR(255) NOT NULL,
  `tehsil` VARCHAR(64) NOT NULL,
  `secretary_name` VARCHAR(255) NOT NULL,
  `lat` DECIMAL(10,7) NOT NULL,
  `lng` DECIMAL(10,7) NOT NULL,
  `accuracy_m` INT UNSIGNED NULL,
  `distance_m` INT UNSIGNED NOT NULL,
  `photo_file` VARCHAR(255) NOT NULL,
  PRIMARY KEY (`id`),
  KEY `idx_uc_no` (`uc_no`),
  KEY `idx_created` (`created_at`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

